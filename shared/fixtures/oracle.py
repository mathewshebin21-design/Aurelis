"""Independent oracle for the quant test cases.

Computes expected values with exact rational arithmetic (fractions.Fraction),
written directly from textbook formulas and sharing no code with either
engine (api/src/aurelis_api/quant, web/src/lib/finance). Both engines'
tests read the JSON this script writes. Simple cases also show the
hand-worked arithmetic in comments.

Regenerate:  python3 shared/fixtures/oracle.py > shared/fixtures/quant-cases.json
"""

from __future__ import annotations

import json
from fractions import Fraction as F


def s(x: F) -> str:
    """Exact fraction → decimal string with 20 significant places (more than any test tolerance)."""
    sign = "-" if x < 0 else ""
    x = abs(x)
    whole = x.numerator // x.denominator
    rem = x - whole
    digits = []
    for _ in range(20):
        rem *= 10
        d = rem.numerator // rem.denominator
        digits.append(str(d))
        rem -= d
    return f"{sign}{whole}.{''.join(digits)}"


def dcf(base_revenue, years, g0, g1, m0, m1, tax, da, capex, nwc, wacc, tg, net_debt, shares):
    """Plain FCFF DCF, end-of-year discounting, linear fades, Gordon terminal value."""
    rows, prev = [], base_revenue
    for i in range(1, years + 1):
        t = F(1) if years == 1 else F(i - 1, years - 1)
        g = g0 + (g1 - g0) * t
        m = m0 + (m1 - m0) * t
        rev = prev * (1 + g)
        ebit = rev * m
        fcff = ebit * (1 - tax) + rev * da - rev * capex - (rev - prev) * nwc
        pv = fcff / (1 + wacc) ** i
        rows.append((rev, fcff, pv))
        prev = rev
    tv = rows[-1][1] * (1 + tg) / (wacc - tg)
    pv_tv = tv / (1 + wacc) ** years
    ev = sum(r[2] for r in rows) + pv_tv
    eq = ev - net_debt
    return {"fcff": [s(r[1]) for r in rows], "terminal_value": s(tv), "pv_terminal_value": s(pv_tv),
            "enterprise_value": s(ev), "equity_value": s(eq), "per_share": s(eq / shares)}


